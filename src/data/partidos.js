function fechaLocal(fecha) {
  const mes = String(fecha.getMonth() + 1).padStart(2, '0');
  const dia = String(fecha.getDate()).padStart(2, '0');
  return `${fecha.getFullYear()}-${mes}-${dia}`;
}

// Separa los partidos: próximos (del más cercano al más lejano) y anteriores (del más reciente al más viejo).
// Con resultado cargado o sin día confirmado, un partido no cuenta como próximo.
export function partidosSeparados(hoy = new Date()) {
  const dia = fechaLocal(hoy);
  const esProximo = (p) => !p.resultado && !p.fechaEsPublicacion && p.fecha >= dia;
  return {
    proximos: partidos.filter(esProximo).sort((a, b) => a.fecha.localeCompare(b.fecha)),
    anteriores: partidos.filter((p) => !esProximo(p)).sort((a, b) => b.fecha.localeCompare(a.fecha)),
  };
}
